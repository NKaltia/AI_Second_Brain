import { GoogleGenAI, Type } from '@google/genai';
import type { Logger } from 'pino';
import { config } from '../config.js';
import {
    GEMINI_CHAT_MODEL,
    GEMINI_EMBEDDING_DIMENSIONS,
    GEMINI_EMBEDDING_MODEL,
} from '../gemini-models.js';
import { intentResultSchema, saveNoteToolArgsSchema } from '../validation/schemas.js';
import type { SaveNoteToolArgs } from '../validation/schemas.js';
import { logger as rootLogger } from '../logger.js';
import {
    ASSISTANT_SYSTEM_INSTRUCTION,
    buildIntentPrompt,
    INVALID_SAVE_NOTE_MESSAGE,
} from '../utils/prompts.js';

export type GenerateAnswerResult = {
    text: string;
    newNoteData?: Pick<SaveNoteToolArgs, 'title' | 'content' | 'tags'>;
};

export class AIService {
    private ai = new GoogleGenAI({ apiKey: config.geminiApiKey });

    async generateEmbedding(text: string, taskType: string = 'RETRIEVAL_QUERY'): Promise<number[]> {
        const response = await this.ai.models.embedContent({
            model: GEMINI_EMBEDDING_MODEL,
            contents: text,
            config: { taskType: taskType, outputDimensionality: GEMINI_EMBEDDING_DIMENSIONS }
        });
        return (response as { embeddings: { values: number[] }[] }).embeddings[0]!.values;
    }

    /**
     * May throw (Gemini / JSON / Zod). Caller decides graceful degradation.
     */
    async analyzeIntentAndExpand(query: string): Promise<{ requiresSearch: boolean; expandedQuery: string }> {
        const response = await this.ai.models.generateContent({
            model: GEMINI_CHAT_MODEL,
            contents: [{ role: 'user', parts: [{ text: buildIntentPrompt(query) }] }],
            config: {
                responseMimeType: 'application/json',
                temperature: 0.1,
            }
        });

        const parsed: unknown = JSON.parse(response.text || '{}');
        const intent = intentResultSchema.parse(parsed);
        return {
            requiresSearch: intent.requiresSearch,
            expandedQuery: intent.expandedQuery,
        };
    }

    async generateAnswer(
        question: string,
        contextNotes: string[],
        history: { role: string; content: string }[] = [],
        log: Logger = rootLogger
    ): Promise<GenerateAnswerResult> {
        const contextText = contextNotes.length > 0 ? contextNotes.join('\n\n---\n\n') : 'No information in the knowledge base';
        const saveNoteTool = {
            functionDeclarations: [
                {
                    name: 'saveNote',
                    description: 'Saves new useful information to the note database. Call this function ONLY if the user ASKS TO SAVE a recipe, generate an article, or asks to remember something important forever.',
                    parameters: {
                        type: Type.OBJECT,
                        properties: {
                            messageToUser: {
                                type: Type.STRING,
                                description: 'A very short, friendly message confirming to the user that the note was successfully saved. MUST be in the same language the user is speaking.'
                            },
                            title: {
                                type: Type.STRING,
                                description: 'Short note title (up to 30 characters)'
                            },
                            content: {
                                type: Type.STRING,
                                description: 'Full text of the note, generated by you, preferably formatted in Markdown'
                            },
                            tags: {
                                type: Type.ARRAY,
                                items: { type: Type.STRING },
                                description: 'List of tags for search (e.g. ["recipes", "code"]'
                            }
                        },
                        required: ['messageToUser', 'title', 'content', 'tags']
                    }
                }
            ]
        };

        const formattedHistory = history.map(msg => ({
            role: msg.role === 'user' ? 'user' : 'model',
            parts: [{ text: msg.content }]
        }));

        const currentMessage = {
            role: 'user',
            parts: [{ text: `Context: ${contextText}\n\nQuestion: ${question}` }]
        };

        const response = await this.ai.models.generateContent({
            model: GEMINI_CHAT_MODEL,
            contents: [...formattedHistory, currentMessage],
            config: {
                systemInstruction: ASSISTANT_SYSTEM_INSTRUCTION,
                tools: [saveNoteTool]
            }
        });

        if (response.functionCalls && response.functionCalls.length > 0) {
            const call = response.functionCalls[0];
            if (call?.name === 'saveNote') {
                const parsed = saveNoteToolArgsSchema.safeParse(call.args);
                if (!parsed.success) {
                    log.warn({ issues: parsed.error.issues }, 'saveNote tool args failed Zod validation');
                    return {
                        text: INVALID_SAVE_NOTE_MESSAGE,
                    };
                }
                const args = parsed.data;
                return {
                    text: args.messageToUser,
                    newNoteData: {
                        title: args.title,
                        content: args.content,
                        tags: args.tags,
                    },
                };
            }
        }
        return {
            text: response.text || 'Error in response',
        };
    }
}
